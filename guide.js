function guideKeys(sid, stepId) {
  const g = STEP_GUIDE[sid + ':' + stepId] || STEP_GUIDE['*:' + stepId];
  return g ? [].concat(g) : [];
}
function guideBtn(sid, stepId, cls = '') {
  const keys = guideKeys(sid, stepId);
  if (!keys.length) return '';
  return `<button class="g-btn ${cls}" data-act="g-open" data-keys="${keys.join(',')}" aria-label="${esc(GUIDE[keys[0]].t)} 운동 방법">${ic('info')}${cls.includes('wide') ? '<span>운동 방법</span>' : ''}</button>`;
}

function renderGuide() {
  const el = document.getElementById('guide');
  if (!ui.guide) { el.hidden = true; el.innerHTML = ''; return; }
  const list = ui.guide.filter(k => GUIDE[k]);
  const sec = (title, items, cls) => items && items.length ? `<h4 class="gd-h ${cls}">${title}</h4><${cls === 'how' ? 'ol' : 'ul'} class="gd-list ${cls}">${items.map(t => `<li>${esc(fill(t))}</li>`).join('')}</${cls === 'how' ? 'ol' : 'ul'}>` : '';
  const ti = tierIdx();
  const lvSec = k => GUIDE_LV[k] ? `<h4 class="gd-h lvh">레벨별 방법 · 내 레벨 ${levelName()}${gradeSys() === 'v' ? '' : ' (V' + lvl() + ')'}</h4><ul class="gd-list lvl">${GUIDE_LV[k].map((t, i) => `<li class="${i === ti ? 'me' : ''}"><b>${PLAN.tiers[i].range}</b> ${esc(t)}</li>`).join('')}</ul>` : '';
  el.hidden = false;
  el.innerHTML = `<div class="sh-back" data-act="g-close"></div><div class="sh-panel" role="dialog" aria-label="운동 방법">
    <div class="sh-grab"></div>
    <div class="sh-h"><h3>${ic('info')}운동 방법</h3><button class="sh-x" data-act="g-close" aria-label="닫기">${ic('close')}</button></div>
    <div class="sh-list gd-body">${list.map(k => { const g = GUIDE[k]; return `<article class="gd">
      <h3 class="gd-t">${esc(g.t)}</h3>
      <p class="gd-aim">${esc(fill(g.aim))}</p>
      ${lvSec(k)}
      ${sec('하는 방법', g.how, 'how')}
      ${sec('핵심 포인트', g.cue, 'cue')}
      ${sec('주의할 점', g.avoid, 'avoid')}
    </article>`; }).join('')}</div>
  </div>`;
}
document.addEventListener('click', e => {
  const b = e.target.closest('[data-act]');
  if (!b) return;
  if (b.dataset.act === 'g-open') { e.stopPropagation(); ui.guide = b.dataset.keys.split(','); renderGuide(); }
  else if (b.dataset.act === 'g-close') { ui.guide = null; renderGuide(); }
});
